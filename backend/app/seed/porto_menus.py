def _rows() -> dict[str, list[tuple[str, str, str, float, str]]]:
    menus = {}
    order = {S: 0, M: 1, D: 2, B: 3}
    for slug, dishes in PORTO_HOUSES.items():
        seen: set[str] = set()
        rows = []
        for name, price in dishes:
            if name in seen:
                continue
            seen.add(name)
            section, description, allergens = DISHES[name]
            rows.append((section, name, description, price, allergens))
        menus[slug] = sorted(rows, key=lambda row: order[row[0]])
    return menus


PORTO_MENUS = _rows()
